#!/usr/bin/env node
/**
 * check-near-duplicates.mjs — ★同名ではない「少し違うだけの重複コード」の増加を数える。
 *
 * ───────────────────────────────────────────────────────────────────────────
 * ■ ★なぜ要るか（2026-09-04・CLAUDE.md基準⑦の機械検出）
 *
 *   「同じ画面が複数箇所に増えるのは、たいてい共通化のサイン」という基準⑦をCLAUDE.mdに
 *   追記したが、文章だけでは検査していない規範と同じ末路をたどる（check-shared-parts-used.mjs
 *   の教訓）。ただし check-shared-parts-used.mjs は【同名】の関数定義しか拾えない。
 *   基準⑦が指す状態は「同じ役割のUIパーツがファイルごとに少しずつ違う実装で出てくる」で、
 *   名前も中身も揃っていない。この検査はその隙間を埋める。
 *
 * ■ ★何を検出するか
 *   対象ファイルを行単位に正規化し、連続5行の窓をハッシュ化。2ファイル以上に出現する窓を
 *   つなげて「12行以上の連続一致の塊」を検出する。3ファイル以上に出る塊はクラスタとしてまとめる。
 *   識別子・文字列リテラル・数値を正規化してから比較するため、変数名を変えただけの
 *   コピー&ペーストも拾える（check-shared-parts-usedが拾えない「名前が違う」型）。
 *
 * ■ ★この検査が判定しないこと（ここが最重要）
 *   ・**統合すべきかは判定しない。** 塊が見つかったからといって共通化が正しいとは限らない。
 *     構造が違う意味的同一（例: ループ vs map）は拾えない。
 *   ・**似ているが違う実装は拾えない。** AST解析はしていない（2026-09-02の設計文書
 *     DESIGN-shared-parts-baseline-2026-09-02.md で「中括弧カウントで誤判定した実績」が
 *     あり、行単位の連続一致に留めた）。
 *   ・**PAIRS宣言済みの意図的複製も数える。** 意図的複製はbaselineに含めて
 *     「増えた分だけ見る」使い方をすること（この検査はラチェットなのでそれで足りる）。
 *   ・**12行未満に割れば数字は下がる。** それを咎める仕組みは無い（閾値をknob化すると
 *     「通すために緩める」が起きるため、意図的に固定にしてある）。
 *
 * ■ ★check-shared-parts-used.mjsとの役割分担（KEEP_SEPARATE、2026-09-07 CANONICAL CHECK）
 *   あちらは「同名関数の定義」という事実、こちらは「似た行の塊」という推測。
 *   事実と推測を混ぜると事実の検査がオオカミ少年になるため、意図的に別ファイルにしている。
 *   詳細: _docs/DESIGN-criterion7-near-duplicate-detection-2026-09-07.md
 *
 * ■ ★強制しない（このキットの掟）
 *   件数の上限はラチェット。増えたときだけ赤。減らすのは自由。
 *
 * ■ ★git 追跡ファイルだけを見る・依存ゼロ
 *   node:crypto と git ls-files のみ。../scripts/lib はimportしない
 *   （templates/diagnostics/ は配布先に単体でコピーされる規約）。
 *
 * ■ 3値の終了コード
 *   0 = 合格 / 1 = ★測れた上での赤（増えた） / 2 = ★測れなかった
 * ───────────────────────────────────────────────────────────────────────────
 *
 * 使い方:
 *   node check-near-duplicates.mjs [対象ディレクトリ] [--baseline N]
 *   node check-near-duplicates.mjs --selftest
 */
import { readFileSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';

const EXIT = Object.freeze({ PASS: 0, FAIL: 1, INCONCLUSIVE: 2 });

const TARGET_EXTENSIONS = ['.js', '.mjs', '.cjs', '.jsx', '.ts', '.tsx', '.html'];
const EXCLUDED = /(^|\/)(node_modules|vendor|third_party|dist|build|out|_backup|\.min\.)/;
const GENERATED_MARKERS = /@generated|自動生成|DO NOT EDIT|generated by/i;
const WINDOW_SIZE = 5;
const MIN_LINES = 12;
const MAX_LINE_LENGTH = 500;

/**
 * ★1ファイルの先頭20行に生成物マーカーがあるか。
 * @param {string} src
 * @returns {boolean}
 */
export function isGeneratedFile(src) {
  const text = typeof src === 'string' ? src : '';
  const head = text.split('\n').slice(0, 20).join('\n');
  return GENERATED_MARKERS.test(head);
}

/**
 * ★1行を正規化する（純粋関数）。
 * コメント除去・文字列リテラルをS・数値を0・識別子をIに置換・空白圧縮。
 * import/export文・短すぎる行・長すぎる行はnullを返し呼び出し側で除外する。
 *
 * @param {string} line
 * @returns {string|null}
 */
export function normalizeLine(line) {
  if (typeof line !== 'string') return null;
  let s = line;

  // ブロック/行コメント・HTMLコメントの除去（行内の断片のみ。複数行コメントの対応はしない=シンプルさ優先）
  s = s.replace(/\/\*.*?\*\//g, '');
  s = s.replace(/\/\/.*$/g, '');
  s = s.replace(/<!--.*?-->/g, '');

  s = s.trim();
  if (s.length === 0) return null;
  if (s.length > MAX_LINE_LENGTH) return null;
  if (/^\s*(import|export\s*\{|export\s+\*|export\s+default\s+from)\b.*\bfrom\b/.test(s)) return null;
  if (/^\s*(import|export)\s/.test(s) && /from\s+['"]/.test(s)) return null;

  // 文字列リテラルをSに置換（エスケープは簡易対応）
  s = s.replace(/"(?:[^"\\]|\\.)*"/g, 'S');
  s = s.replace(/'(?:[^'\\]|\\.)*'/g, 'S');
  s = s.replace(/`(?:[^`\\]|\\.)*`/g, 'S');

  // 数値をゼロに置換
  s = s.replace(/\b\d+(\.\d+)?\b/g, '0');

  // 識別子をIに置換（JS予約語は除く）
  const RESERVED = new Set([
    'const', 'let', 'var', 'function', 'return', 'if', 'else', 'for', 'while', 'do',
    'switch', 'case', 'break', 'continue', 'default', 'new', 'delete', 'typeof',
    'instanceof', 'in', 'of', 'this', 'super', 'class', 'extends', 'static', 'get',
    'set', 'async', 'await', 'yield', 'try', 'catch', 'finally', 'throw', 'null',
    'undefined', 'true', 'false', 'void', 'import', 'export', 'from', 'as', 'default',
  ]);
  s = s.replace(/[A-Za-z_$][\w$]*/g, (m) => (RESERVED.has(m) ? m : 'I'));

  s = s.replace(/\s+/g, ' ').trim();
  if (s.length < 4) return null;

  return s;
}

/**
 * ★1ファイルの内容から、正規化済みの行配列（元の行番号つき）を作る。
 * @param {string} src
 * @returns {{line:number, norm:string}[]}
 */
export function extractNormalizedLines(src) {
  const text = typeof src === 'string' ? src : '';
  const rawLines = text.replace(/\r\n/g, '\n').split('\n');
  const out = [];
  for (let i = 0; i < rawLines.length; i++) {
    const norm = normalizeLine(rawLines[i]);
    if (norm !== null) out.push({ line: i + 1, norm });
  }
  return out;
}

/**
 * ★正規化済み行配列から、連続WINDOW_SIZE行の窓ハッシュ列を作る。
 * @param {{line:number, norm:string}[]} normLines
 * @returns {{hash:string, startLine:number}[]}
 */
export function buildWindows(normLines) {
  const windows = [];
  for (let i = 0; i + WINDOW_SIZE <= normLines.length; i++) {
    const chunk = normLines.slice(i, i + WINDOW_SIZE);
    const text = chunk.map((l) => l.norm).join('\n');
    const hash = createHash('sha1').update(text).digest('hex');
    windows.push({ hash, startLine: chunk[0].line });
  }
  return windows;
}

/**
 * ★判定の本体（fsにもgitにも触らない＝テストできる）。
 *
 * @param {{path:string, windows:{hash:string, startLine:number}[]}[]} files
 * @param {number|null} baseline 既知の塊数（ラチェットの上限）。nullなら初回として現在値を上限にする。
 * @returns {{verdict:'pass'|'fail'|'inconclusive', clusters:{files:string[], startLines:Record<string,number>, lineCount:number}[], reason?:string, limit?:number}}
 */
export function judgeNearDuplicates(files, baseline) {
  const list = Array.isArray(files) ? files : [];

  if (list.length < 2) {
    return {
      verdict: 'inconclusive',
      clusters: [],
      reason: '走査対象が2ファイル未満です（★比べる相手がありません）',
    };
  }

  // 転置索引: ハッシュ → [{path, startLine}]
  const index = new Map();
  for (const f of list) {
    for (const w of f.windows || []) {
      if (!index.has(w.hash)) index.set(w.hash, []);
      index.get(w.hash).push({ path: f.path, startLine: w.startLine });
    }
  }

  // 2ファイル以上に出現する窓だけを残す
  const sharedHashes = new Set();
  for (const [hash, occ] of index) {
    const distinctPaths = new Set(occ.map((o) => o.path));
    if (distinctPaths.size >= 2) sharedHashes.add(hash);
  }

  // ファイルごとに「共有窓の開始行」を集め、連続する開始行を塊としてつなげる
  const fileWindowMap = new Map(); // path -> Set(startLine) for shared windows
  for (const f of list) {
    const starts = new Set();
    for (const w of f.windows || []) {
      if (sharedHashes.has(w.hash)) starts.add(w.startLine);
    }
    if (starts.size > 0) fileWindowMap.set(f.path, [...starts].sort((a, b) => a - b));
  }

  // 各ファイル内で連続する開始行をブロックにまとめ、対応するハッシュ列でグループ化する
  // ブロックの「シグネチャ」= そのブロックが含む窓ハッシュの並び（順序込み）。
  // 同じシグネチャを持つブロックが複数ファイルにあればクラスタとして採用する。
  const hashByStart = new Map(); // path -> Map(startLine -> hash)
  for (const f of list) {
    const m = new Map();
    for (const w of f.windows || []) m.set(w.startLine, w.hash);
    hashByStart.set(f.path, m);
  }

  const blockSignatures = new Map(); // signature -> [{path, startLine, lineCount}]
  for (const [path, starts] of fileWindowMap) {
    let blockStart = starts[0];
    let prev = starts[0];
    let sigHashes = [hashByStart.get(path).get(starts[0])];

    const flush = (endStart) => {
      const lineCount = (endStart - blockStart) + WINDOW_SIZE;
      if (lineCount >= MIN_LINES) {
        const sig = sigHashes.join('|');
        if (!blockSignatures.has(sig)) blockSignatures.set(sig, []);
        blockSignatures.get(sig).push({ path, startLine: blockStart, lineCount });
      }
    };

    for (let i = 1; i < starts.length; i++) {
      const cur = starts[i];
      if (cur === prev + 1) {
        sigHashes.push(hashByStart.get(path).get(cur));
        prev = cur;
      } else {
        flush(prev);
        blockStart = cur;
        prev = cur;
        sigHashes = [hashByStart.get(path).get(cur)];
      }
    }
    flush(prev);
  }

  // 同じシグネチャで3ファイル以上に出るものをクラスタとして採用（2ファイルの一致も1クラスタとして数える）
  const clusters = [];
  for (const [, occurrences] of blockSignatures) {
    const distinctPaths = new Set(occurrences.map((o) => o.path));
    if (distinctPaths.size < 2) continue;
    const startLines = {};
    for (const o of occurrences) startLines[o.path] = o.startLine;
    clusters.push({
      files: [...distinctPaths],
      startLines,
      lineCount: occurrences[0].lineCount,
    });
  }

  const limit = Number.isFinite(baseline) ? baseline : clusters.length;
  return {
    verdict: clusters.length > limit ? 'fail' : 'pass',
    clusters,
    limit,
  };
}

// ── selftest（★毒→赤） ──────────────────────────────────────────────────
function runSelftest() {
  const fails = [];

  const mkFile = (path, lines) => {
    const normLines = lines.map((norm, i) => ({ line: i + 1, norm }));
    return { path, windows: buildWindows(normLines) };
  };

  // 15行の同一パターン（識別子だけ違うが正規化後は同じ）を2ファイルに用意
  const pattern15 = Array.from({ length: 15 }, (_, i) => `const I = I(${i});`);

  // ① 識別子・文字列を変えただけの15行×2ファイル → 塊1件
  {
    const a = mkFile('a.js', pattern15);
    const b = mkFile('b.js', pattern15);
    const r = judgeNearDuplicates([a, b], 0);
    if (r.verdict !== 'fail') fails.push('★15行の一致を見逃す');
    if (r.clusters.length !== 1) fails.push(`★クラスタ数が1でない: ${r.clusters.length}`);
  }

  // ② 同一だが8行 → 0件（閾値未満）
  {
    const pattern8 = Array.from({ length: 8 }, (_, i) => `const I = I(${i});`);
    const a = mkFile('a.js', pattern8);
    const b = mkFile('b.js', pattern8);
    const r = judgeNearDuplicates([a, b], 0);
    if (r.clusters.length !== 0) fails.push('★8行(閾値未満)を塊として数えている');
  }

  // ③ コメントだけ同一 → 0件
  {
    const commentLines = Array.from({ length: 15 }, () => '// same comment');
    const a = { path: 'a.js', windows: buildWindows(extractNormalizedLines(commentLines.join('\n'))) };
    const b = { path: 'b.js', windows: buildWindows(extractNormalizedLines(commentLines.join('\n'))) };
    const r = judgeNearDuplicates([a, b], 0);
    if (r.clusters.length !== 0) fails.push('★コメントのみの一致を数えている');
  }

  // ④ 同じ塊が3ファイル → クラスタ1件・所在3箇所
  {
    const a = mkFile('a.js', pattern15);
    const b = mkFile('b.js', pattern15);
    const c = mkFile('c.js', pattern15);
    const r = judgeNearDuplicates([a, b, c], 0);
    if (r.clusters.length !== 1) fails.push('★3ファイル一致が1クラスタにまとまらない');
    if (r.clusters[0]?.files.length !== 3) fails.push('★3ファイル分の所在が記録されていない');
  }

  // ⑤ 生成物マーカー付きファイル → 除外され数えない（isGeneratedFileの単体確認）
  {
    const genSrc = '// @generated by tool\n' + pattern15.join('\n');
    if (!isGeneratedFile(genSrc)) fails.push('★生成物マーカーを検出できない');
    if (isGeneratedFile(pattern15.join('\n'))) fails.push('★生成物でないものを生成物と誤検知する');
  }

  // ⑥ count > baseline → fail／≤ → pass／baseline無し → pass
  {
    const a = mkFile('a.js', pattern15);
    const b = mkFile('b.js', pattern15);
    const rFail = judgeNearDuplicates([a, b], 0);
    if (rFail.verdict !== 'fail') fails.push('★baseline超過なのに赤くならない');
    const rPass = judgeNearDuplicates([a, b], 1);
    if (rPass.verdict !== 'pass') fails.push('★baseline以内なのに赤くする');
    const rNoBaseline = judgeNearDuplicates([a, b], null);
    if (rNoBaseline.verdict !== 'pass') fails.push('★baseline未設定(初回)なのに赤くする');
  }

  // ⑦ ファイル2件未満 → inconclusive
  {
    const a = mkFile('a.js', pattern15);
    const r = judgeNearDuplicates([a], 0);
    if (r.verdict !== 'inconclusive') fails.push('★1ファイルのみをinconclusiveにしない');
  }

  // ⑧ null入力でthrowしない
  {
    try {
      const r = judgeNearDuplicates(null, null);
      if (r.verdict !== 'inconclusive') fails.push('★nullをinconclusiveにしない');
    } catch {
      fails.push('★壊れた入力でthrowする');
    }
  }

  if (fails.length) {
    console.error('[check-near-duplicates] ★selftest 失敗（検知器が効いていません）:');
    for (const f of fails) console.error(`  - ${f}`);
    process.exit(EXIT.FAIL);
  }
  console.log(
    '[check-near-duplicates] ✅ selftest 合格'
    + '（8件: 一致検出/閾値/コメント除外/複数ファイル/生成物除外/ラチェット/inconclusive/null安全）',
  );
  process.exit(EXIT.PASS);
}

// ── 実行 ────────────────────────────────────────────────────────────────
const isMain = Boolean(process.argv[1]) && pathToFileURL(process.argv[1]).href === import.meta.url;

if (isMain && process.argv.includes('--selftest')) runSelftest();

if (isMain) {
  const argDir = process.argv.slice(2).find((a, i, arr) => !a.startsWith('--') && arr[i - 1] !== '--baseline');
  const root = resolve(argDir || process.cwd());

  const baselineArgIdx = process.argv.indexOf('--baseline');
  const baselineArg = baselineArgIdx >= 0 ? Number(process.argv[baselineArgIdx + 1]) : null;
  const baseline = Number.isFinite(baselineArg) ? baselineArg : null;

  let tracked;
  try {
    tracked = execFileSync(
      'git',
      ['ls-files', ...TARGET_EXTENSIONS.map((ext) => `*${ext}`)],
      { cwd: root, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
    ).split('\n').map((s) => s.trim()).filter(Boolean);
  } catch (e) {
    console.error('[check-near-duplicates] 🟡 git ls-files を実行できませんでした（★緑ではありません）。');
    console.error(`  → 理由: ${e && e.message}`);
    process.exit(EXIT.INCONCLUSIVE);
  }

  const scannable = tracked.filter((p) => !EXCLUDED.test(p));

  let generatedCount = 0;
  const files = [];
  for (const p of scannable) {
    let src;
    try { src = readFileSync(join(root, p), 'utf8'); } catch { continue; }
    if (isGeneratedFile(src)) { generatedCount++; continue; }
    const normLines = extractNormalizedLines(src);
    const windows = buildWindows(normLines);
    if (windows.length > 0) files.push({ path: p, windows });
  }

  const r = judgeNearDuplicates(files, baseline);

  if (r.verdict === 'inconclusive') {
    console.error(`[check-near-duplicates] 🟡 測れませんでした: ${r.reason}`);
    process.exit(EXIT.INCONCLUSIVE);
  }

  const sorted = [...r.clusters].sort((a, b) => (b.files.length - a.files.length) || (b.lineCount - a.lineCount));

  console.log(
    `[check-near-duplicates] 走査 ${scannable.length} ファイル（生成物として除外 ${generatedCount}）`
    + ` / ★${MIN_LINES}行以上の似た塊 ${r.clusters.length} 件`
    + (baseline === null ? '（ベースライン未設定）' : `（上限 ${r.limit}）`),
  );
  for (const c of sorted.slice(0, 10)) {
    const locations = c.files.map((f) => `${f}:${c.startLines[f]}-${c.startLines[f] + c.lineCount - 1}`);
    console.log(`  ⚪ ${c.files.length}ファイル × ${c.lineCount}行: ${locations.join(' ≈ ')}`);
  }
  if (sorted.length > 10) console.log(`  （他 ${sorted.length - 10} 件）`);

  console.log('  → 直し方: 共有置き場（scripts/lib・shared/ 等）へ切り出して両方から呼ぶ。');
  console.log('    ★意図的な複製（配布境界をまたぐ等）なら PAIRS に登録し、baseline を上げて理由をコミットに書く。');
  console.log('  → ★この検査が判定しないこと: 統合すべきか／構造が違う同目的コードは見ません。');

  if (r.verdict === 'fail') {
    console.error('[check-near-duplicates] 🔴 似た塊が増えました。');
    if (baseline === null) {
      console.error(`  → 初回: --baseline ${r.clusters.length} として記録してください。`);
    }
    process.exit(EXIT.FAIL);
  }

  if (baseline === null) {
    console.log(`[check-near-duplicates] ✅ 合格（初回: --baseline ${r.clusters.length} として記録してください）。`);
  } else {
    console.log('[check-near-duplicates] ✅ 合格（増えていません）。');
  }
  process.exit(EXIT.PASS);
}
